// Extracts a poster frame from every clip in public/videos and writes both the
// JPEGs (public/images/video-posters) and the manifest AutoVideo and the
// VideoObject schema read (src/lib/videoPosters.ts).
//
// A one-off maintenance script, not part of `npm run build`: the posters it
// produces are committed, so a normal build — and Vercel — never needs ffmpeg.
// Run it after adding a clip:
//
//   npm i -D ffmpeg-static && node scripts/generate-video-posters.mjs
//
// Why posters exist at all: a <video> with no poster paints a black box until
// it buffers, and Google refuses to index a video it cannot get a thumbnail
// for. One frame fixes both.
import { execFile } from "node:child_process"
import { readdir, writeFile, mkdir } from "node:fs/promises"
import { promisify } from "node:util"
import path from "node:path"
import { fileURLToPath } from "node:url"

const run = promisify(execFile)
const root = path.resolve(fileURLToPath(import.meta.url), "../..")
const videosDir = path.join(root, "public/videos")
const postersDir = path.join(root, "public/images/video-posters")
const manifestPath = path.join(root, "src/lib/videoPosters.ts")

// A frame this far into the clip rather than frame 0: openings often fade up
// from black, and a black poster is worse than none.
const POSTER_POSITION = 0.15

async function ffmpegPath() {
  const mod = await import("ffmpeg-static").catch(() => null)
  if (mod?.default) return mod.default
  return "ffmpeg" // fall back to whatever is on PATH
}

async function durationSeconds(ffmpeg, file) {
  // ffmpeg (not ffprobe) so the static package alone is enough to run this.
  const { stderr } = await run(ffmpeg, ["-i", file]).catch((err) => err)
  const match = /Duration:\s*(\d+):(\d+):(\d+\.\d+)/.exec(stderr ?? "")
  if (!match) throw new Error(`Could not read the duration of ${file}`)
  return Number(match[1]) * 3600 + Number(match[2]) * 60 + Number(match[3])
}

export async function generatePosters({ log = console.log } = {}) {
  const ffmpeg = await ffmpegPath()
  await mkdir(postersDir, { recursive: true })

  const clips = (await readdir(videosDir)).filter((f) => f.endsWith(".mp4")).sort()
  const entries = []

  for (const clip of clips) {
    const source = path.join(videosDir, clip)
    const name = clip.replace(/\.mp4$/, "")
    const outFile = path.join(postersDir, `${name}.jpg`)
    const seconds = await durationSeconds(ffmpeg, source)
    const seek = seconds * POSTER_POSITION

    await run(ffmpeg, [
      "-y",
      "-ss", seek.toFixed(2),
      "-i", source,
      "-frames:v", "1",
      // Downscale wide clips only; portrait clips keep their height. -2 keeps
      // the other axis even, which JPEG chroma subsampling requires.
      "-vf", "scale='min(1280,iw)':-2",
      "-q:v", "4",
      outFile,
    ])

    entries.push({
      src: `/videos/${clip}`,
      poster: `/images/video-posters/${name}.jpg`,
      // ISO 8601, the only form schema.org's `duration` accepts.
      duration: `PT${Math.round(seconds)}S`,
    })
    log(`poster: ${clip} -> ${path.relative(root, outFile)} @ ${seek.toFixed(2)}s`)
  }

  const body = entries
    .map((e) => `  "${e.src}": { poster: "${e.poster}", duration: "${e.duration}" },`)
    .join("\n")
  await writeFile(
    manifestPath,
    `// Generated by scripts/generate-video-posters.mjs. Do not edit by hand.
//
// Maps each clip in public/videos to its extracted poster frame and its
// measured length. AutoVideo looks a video up here when no explicit poster is
// passed, so a clip with no entry behaves exactly as it did before posters
// existed rather than requesting an image that isn't there.
export type VideoAsset = { poster: string; duration: string }

export const VIDEO_ASSETS: Record<string, VideoAsset> = {
${body}
}

export function posterFor(src: string): string | undefined {
  return VIDEO_ASSETS[src]?.poster
}

/** ISO 8601 length, for schema.org's \`duration\`. */
export function durationFor(src: string): string | undefined {
  return VIDEO_ASSETS[src]?.duration
}
`,
    "utf-8"
  )
  log(`manifest: ${path.relative(root, manifestPath)} (${entries.length} clips)`)
  return entries
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generatePosters().catch((err) => {
    console.error(err)
    process.exit(1)
  })
}
